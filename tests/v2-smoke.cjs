/* Prueba reproducible sin datos reales. Ejecuta con node tests/v2-smoke.cjs */
const assert=require('node:assert/strict');
const fs=require('node:fs');
const {webcrypto}=require('node:crypto');
const {JSDOM}=require('jsdom');
const html=fs.readFileSync('index.html','utf8');
const dom=new JSDOM(html,{url:'https://example.test/Arkeo-caja13/',runScripts:'outside-only',pretendToBeVisual:true});
const w=dom.window,d=w.document;
Object.defineProperty(w,'crypto',{configurable:true,value:webcrypto});
w.matchMedia=()=>({matches:false,addListener(){},removeListener(){}});
w.scrollTo=()=>{};
w.confirm=()=>true;
w.alert=()=>{};
w.print=()=>{};
let fatal=[];
w.addEventListener('error',e=>fatal.push(e.message));
process.on('unhandledRejection',e=>fatal.push(String(e)));
const get=s=>{const x=d.querySelector(s);assert.ok(x,'Elemento ausente: '+s);return x};
const set=(s,v)=>{const e=get(s);e.value=v;e.dispatchEvent(new w.Event('input',{bubbles:true}));return e};
const click=s=>get(s).click();
const send=s=>{const e=get(s);e.dispatchEvent(new w.Event('submit',{bubbles:true,cancelable:true}))};
const wait=async(n=180)=>new Promise(r=>setTimeout(r,n));
const state=()=>w.eval('state');
const shift=()=>w.eval('activeShift()');
const amount=()=>w.eval('shiftExpected(activeShift())');
(async()=>{
 w.eval(fs.readFileSync('app.js','utf8'));
 w.eval(fs.readFileSync('cashier-v2.js','utf8'));
 assert.match(d.querySelector('#app').textContent,/Configura el acceso/);
 set('#setup-name','Responsable prueba');
 set('#pin-code','123456');
 set('#pin-repeat','123456');
 send('#pin-setup-form');await wait(500);
 assert.equal(state().auth.operators.length,1,'Debe existir administrador');
 assert.equal(state().auth.operators[0].hash.includes('123456'),false,'No guardar PIN legible');
 assert.ok(get('#open-shift-form'),'Pantalla de abrir turno tras configurar PIN');
 click('[data-v2="count-start"][data-mode="opening"][data-step="bill"]');
 assert.match(d.body.textContent,/Cuenta los billetes/);
 set('[name="counter_b2000"]','2');
 click('[data-v2="counter-next"]');
 set('[name="counter_m500"]','1');
 click('[data-v2="counter-next"]');
 assert.match(d.querySelector('.v2-review-amount').textContent,/4.500/);
 click('[data-v2="counter-next"]');
 assert.ok(!get('#open-shift-form button[type=submit]').disabled);
 send('#open-shift-form');await wait(80);
 assert.ok(shift(),'Caja abierta');
 assert.equal(shift().base,4500);
 assert.equal(shift().operator,'Responsable prueba');
 assert.match(d.body.textContent,/¿Qué vas a hacer/);
 click('.v2-lock');assert.ok(get('#pin-login-form'));
 set('#pin-code','111111');send('#pin-login-form');await wait(350);
 assert.ok(get('#pin-login-form'),'PIN incorrecto bloquea');
 set('#pin-code','123456');send('#pin-login-form');await wait(350);
 assert.ok(get('.v2-cash-hero'),'Reingreso correcto');
 click('.v2-action[data-page-target="registrar"][data-tab="venta"]');
 assert.ok(get('#document-form'));
 set('#document-form [name="party"]','Cliente Prueba');
 set('#document-form [name="total"]','10000');
 set('#document-form [name="pay_amount"]','6000');
 send('#document-form');await wait(50);
 assert.equal(state().documents.length,1);
 assert.equal(amount(),10500);
 assert.equal(w.eval('outstanding("sale")'),4000,'Crédito pendiente');
 click('[data-page="inicio"]');
 click('[data-action="show-close"]');
 assert.ok(get('#close-form'));
 click('[data-v2="count-start"][data-mode="closing"][data-step="bill"]');
 set('[name="counter_b10000"]','1');
 click('[data-v2="counter-next"]');
 set('[name="counter_m500"]','1');
 click('[data-v2="counter-next"]');click('[data-v2="counter-next"]');
 assert.ok(!get('#close-form button[type=submit]').disabled);
 set('#close-form [name="nextBase"]','4500');
 send('#close-form');await wait(80);
 assert.equal(shift(),null,'Caja debe quedar cerrada');
 assert.equal(state().shifts[0].difference,0);
 assert.equal(state().shifts[0].nextBase,4500);
 click('[data-action="close-modal"]');
 click('[data-page="ajustes"]');
 set('#v2-person-name','Cajero Dos');
 set('#v2-person-pin','9090');
 send('#v2-add-operator');await wait(450);
 assert.equal(state().auth.operators.length,2,'Debe crear un segundo usuario');
 click('.v2-lock');assert.ok(get('#pin-login-form'));
 get('#pin-person').value=state().auth.operators[1].id;
 set('#pin-code','9090');send('#pin-login-form');await wait(350);
 assert.ok(get('#open-shift-form'),'Cajero entra a su caja');
 assert.equal(d.querySelector('[data-page="ajustes"]'),null,'Cajero sin acceso visible a ajustes');
 assert.deepEqual(fatal,[],'No debe haber errores de JavaScript');
 console.log('PASS: PIN administrador, bloqueo, cajero, apertura, venta parcial, crédito y cierre por modales');
})().catch(err=>{console.error(err);process.exitCode=1}).finally(()=>dom.window.close());
